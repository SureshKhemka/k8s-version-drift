"""Code-generated message parts (FR-19..FR-24). Nothing in this module is written or edited by an LLM.

Final message layout:
    [mentions line]          FR-23, only when CRITICAL findings exist
    body                     LLM draft, fallback template, or all-clear
    appendix                 FR-19, every CRITICAL finding and every UNREACHABLE cluster
    footer                   FR-20
"""

from __future__ import annotations

from dataclasses import dataclass, field
from datetime import date
from typing import Literal

from drift.diff.tagging import ChangeSet
from drift.domain.enums import ChangeTag, Rule, Severity
from drift.rules.base import Finding
from drift.rules.engine import Detection

SummarySource = Literal["llm", "fallback", "all_clear"]
Format = Literal["slack_mrkdwn", "plain"]

STATUS_ICON = {
    Severity.CRITICAL: "🔴",
    Severity.HIGH: "🟠",
    Severity.MEDIUM: "🟡",
    Severity.LOW: "🟢",
    Severity.INFO: "🟢",
}


@dataclass(frozen=True)
class Fmt:
    kind: Format

    def bold(self, s: str) -> str:
        return f"*{s}*" if self.kind == "slack_mrkdwn" else s

    def italic(self, s: str) -> str:
        return f"_{s}_" if self.kind == "slack_mrkdwn" else s

    def text(self, s: str) -> str:
        """Escape data for the channel (Slack treats &, <, > as control characters)."""
        if self.kind == "slack_mrkdwn":
            return s.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")
        return s


@dataclass(frozen=True)
class RunFacts:
    """Run-level numbers every message part may state. Also part of the Gate 2 fact sheet."""

    run_id: str
    run_date: date
    total: int
    checked: int
    compliant: int
    unreachable: int
    clusters_with_findings: int
    matrix_version: str
    first_run: bool
    severity_counts: dict[Severity, int] = field(default_factory=dict)
    change_counts: dict[ChangeTag, int] = field(default_factory=dict)
    new_clusters: int = 0

    @classmethod
    def build(cls, run_id: str, run_date: date, det: Detection, changes: ChangeSet, matrix_version: str) -> RunFacts:
        return cls(
            run_id=run_id,
            run_date=run_date,
            total=det.total,
            checked=det.checked,
            compliant=len(det.compliant),
            unreachable=sum(1 for f in det.findings if f.rule is Rule.UNREACHABLE),
            clusters_with_findings=len({f.cluster_id for f in det.findings}),
            matrix_version=matrix_version,
            first_run=changes.first_run,
            severity_counts=det.by_severity(),
            change_counts=dict(changes.counts),
            new_clusters=len(changes.new_clusters),
        )

    @property
    def top_severity(self) -> Severity | None:
        return next((s for s in sorted(Severity, reverse=True) if self.severity_counts.get(s)), None)


def n(count: int, word: str) -> str:
    return f"{count} {word}" if count == 1 else f"{count} {word}s"


def is_all_clear(findings: tuple[Finding, ...] | list[Finding]) -> bool:
    """FR-21: nothing at MEDIUM or above and nothing unreachable."""
    return not any(f.severity >= Severity.MEDIUM or f.rule is Rule.UNREACHABLE for f in findings)


def appendix_findings(findings: tuple[Finding, ...] | list[Finding]) -> list[Finding]:
    """FR-19 selection: every CRITICAL finding and every UNREACHABLE cluster, in severity order."""
    return [f for f in findings if f.severity is Severity.CRITICAL or f.rule is Rule.UNREACHABLE]


def appendix_line(f: Finding, fmt: Fmt) -> str:
    where = f.cluster_name if f.subject in ("control-plane", "cluster") else f"{f.cluster_name} / {f.subject}"
    parts = [fmt.text(where), f.rule.value, fmt.text(f.observed)]
    if f.limit:
        parts.append(f"limit {fmt.text(f.limit)}")
    if f.nodes_affected is not None:
        parts.append(n(f.nodes_affected, "node"))
    return "• " + " — ".join(parts)


def appendix(findings: tuple[Finding, ...] | list[Finding], fmt: Fmt) -> str:
    rows = appendix_findings(findings)
    if not rows:
        return ""
    return "\n".join([fmt.bold("Critical and unreachable (generated by code)"), *(appendix_line(f, fmt) for f in rows)])


def footer(facts: RunFacts, source: SummarySource, fmt: Fmt, model: str | None = None) -> str:
    summary = {
        "llm": f"LLM-written ({model})" if model else "LLM-written",
        "fallback": "fallback (code-generated)",
        "all_clear": "all clear (code-generated)",
    }[source]
    return fmt.italic(
        f"Run date {facts.run_date.isoformat()} · checked {facts.checked}/{facts.total} clusters · "
        f"{facts.compliant} compliant · matrix {fmt.text(facts.matrix_version)} · summary: {summary} · "
        f"run ID {facts.run_id}"
    )


def mentions_line(findings: tuple[Finding, ...] | list[Finding], mentions: tuple[str, ...]) -> str:
    """FR-23: decided by code, only when CRITICAL findings exist."""
    if not mentions or not any(f.severity is Severity.CRITICAL for f in findings):
        return ""
    return " ".join(mentions)


def status_line(facts: RunFacts, fmt: Fmt) -> str:
    top = facts.top_severity
    icon = STATUS_ICON[top] if top else "✅"
    counts = " · ".join(
        f"{facts.severity_counts[s]} {s.name}" for s in sorted(Severity, reverse=True) if facts.severity_counts.get(s)
    )
    total = sum(facts.severity_counts.values())
    line = f"{icon} {counts} ({n(total, 'finding')}) on {n(facts.clusters_with_findings, 'cluster')}"
    if facts.unreachable:
        line += f"; {n(facts.unreachable, 'cluster')} unreachable"
    return line + "."


def changes_line(facts: RunFacts) -> str:
    if facts.first_run:
        return "First run: there is no previous run to compare with, so every finding is new."
    c = facts.change_counts
    parts = [
        f"{c.get(ChangeTag.NEW, 0)} new",
        f"{c.get(ChangeTag.WORSENED, 0)} worsened",
        f"{c.get(ChangeTag.RESOLVED, 0)} resolved",
    ]
    if facts.new_clusters:
        parts.append(n(facts.new_clusters, "new cluster"))
    return "Since last run: " + " · ".join(parts) + "."


def title(facts: RunFacts, fmt: Fmt) -> str:
    return fmt.bold(f"Kubernetes version drift — {facts.run_date.isoformat()}")


def fallback_body(facts: RunFacts, fmt: Fmt) -> str:
    """FR-22: status line, counts by severity, NEW/WORSENED/RESOLVED counts. The appendix follows separately."""
    return "\n".join([title(facts, fmt), status_line(facts, fmt), changes_line(facts)])


def all_clear_body(facts: RunFacts, fmt: Fmt) -> str:
    low = facts.severity_counts.get(Severity.LOW, 0)
    extra = f" {n(low, 'LOW finding')} not shown." if low else ""
    return "\n".join(
        [
            title(facts, fmt),
            f"✅ All clear: {facts.checked}/{facts.total} clusters checked, nothing at MEDIUM or above, "
            f"nothing unreachable.{extra}",
        ]
    )


def assemble(mentions: str, body: str, appendix_text: str, footer_text: str) -> str:
    return "\n\n".join(part for part in (mentions, body, appendix_text, footer_text) if part)


def body_budget(max_length: int, mentions: str, appendix_text: str, footer_text: str) -> int:
    """Characters left for the body once the code-generated parts are placed (never negative)."""
    fixed = len(assemble(mentions, "", appendix_text, footer_text))
    separators = 2 if fixed else 0
    return max(0, max_length - fixed - separators)
